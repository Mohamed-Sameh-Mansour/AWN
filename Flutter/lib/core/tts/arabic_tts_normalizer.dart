  static const Map<String, String> _phraseMap = {
    'نص جنيه': 'نُصّ جُنَيْه',
    'نص جنية': 'نُصّ جُنَيْه',
    'ربع جنيه': 'رُبْع جُنَيْه',
    'ربع جنية': 'رُبْع جُنَيْه',
    'قريب جدا': 'قَريب جِدًّا',
    'قريب جدًا': 'قَريب جِدًّا',
  };

  static String prepare(String text) {
    if (text.trim().isEmpty) return text;

    var prepared = text;

    for (final entry in _phraseMap.entries) {
      prepared = prepared.replaceAll(entry.key, entry.value);
    }

    final output = StringBuffer();
    final token = StringBuffer();

    void flushToken() {
      if (token.isEmpty) return;

      final word = token.toString();
      output.write(_wordMap[word] ?? word);
      token.clear();
    }

    for (final rune in prepared.runes) {
      if (_isArabicRune(rune)) {
        token.writeCharCode(rune);
      } else {
        flushToken();
        output.writeCharCode(rune);
      }
    }

    flushToken();

    return output.toString();
  }

  static bool _isArabicRune(int rune) {
    return (rune >= 0x0600 && rune <= 0x06FF) ||
        (rune >= 0x0750 && rune <= 0x077F) ||
        (rune >= 0x08A0 && rune <= 0x08FF) ||
        (rune >= 0xFB50 && rune <= 0xFDFF) ||
        (rune >= 0xFE70 && rune <= 0xFEFF);
  }
